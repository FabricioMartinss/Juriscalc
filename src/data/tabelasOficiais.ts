/**
 * Função de busca de índices oficiais do TJSP dinâmica por Tipo de Tabela.
 * Retorna o valor exato correspondente ao ano e mês informados.
 * Trata as datas limites de início e fim.
 */
export function buscarIndiceOficial(
  tabela: TipoTabelaCorrecao,
  ano: number,
  mes: number
): { value: number; found: boolean } {
  // 1. Caso IPCA-E
  if (tabela === 'ipca_e') {
    if (ano < 1992) {
      return { value: 1.000000, found: false };
    }
    const valoresAno = TABELA_IPCA_E[ano];
    if (valoresAno) {
      const val = valoresAno[mes - 1];
      if (val !== undefined) {
        return { value: val, found: true };
      }
    }
    // Fallback se pós-2026
    return { value: 8.432857, found: false };
  }

  // 2. Tabela de Débitos Judiciais comum (Nova lei ou Antiga)
  // Período anterior a Setembro de 2024 é IDENTICO entre as duas tabelas
  if (ano === 1964) {
    if (mes >= 10 && mes <= 12) {
      // OUT (index 0), NOV (index 1), DEZ (index 2)
      return { value: BASE_TABELA_COMUM[1964][mes - 10], found: true };
    }
    return { value: 10000.00, found: false };
  }
  if (ano < 1964) {
    return { value: 10000.00, found: false };
  }

  // Se for antes de Setembro de 2024
  const isSuficientementeAntigo = ano < 2024 || (ano === 2024 && mes < 9);
  
  if (isSuficientementeAntigo) {
    const valoresAno = BASE_TABELA_COMUM[ano];
    if (valoresAno) {
      const val = valoresAno[mes - 1];
      if (val !== undefined) {
        return { value: val, found: true };
      }
    }
  } else {
    // Período de Setembro de 2024 onwards: bifurcação
    if (tabela === 'nova_tabela') {
      const valoresAno = NOVA_TABELA_PÓS_2024[ano];
      if (valoresAno) {
        const offset = ano === 2024 ? 9 : 1; // 2024 começa no mês 9 (index 0)
        const val = valoresAno[mes - offset];
        if (val !== undefined) {
          return { value: val, found: true };
        }
      }
      return { value: 103.784200, found: false }; // Final 2026/05
    } else {
      // antiga_tabela
      const valoresAno = ANTIGA_TABELA_PÓS_2024[ano];
      if (valoresAno) {
        const offset = ano === 2024 ? 9 : 1;
        const val = valoresAno[mes - offset];
        if (val !== undefined) {
          return { value: val, found: true };
        }
      }
      return { value: 103.550000, found: false }; // Final antiga 2026/05
    }
  }

  // Fallback seguro
  return { value: 103.784200, found: false };
}
